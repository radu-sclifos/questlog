CREATE TABLE genres
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    igdb_id BIGINT UNIQUE,
    name    TEXT NOT NULL
);

CREATE TABLE companies
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    igdb_id BIGINT UNIQUE,
    name    TEXT NOT NULL
);

CREATE TABLE engines
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    igdb_id BIGINT UNIQUE,
    name    TEXT NOT NULL
);

CREATE TABLE franchises
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    igdb_id BIGINT UNIQUE,
    name    TEXT NOT NULL
);

CREATE TABLE game_types
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    igdb_id BIGINT UNIQUE,
    name    TEXT NOT NULL
