-- #####  GAMES  #####
CREATE TABLE games
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(200)             NOT NULL,
    igdb_id            BIGINT UNIQUE,
    first_release_date DATE,
    summary            TEXT,
    storyline          TEXT,
    game_type_id       BIGINT REFERENCES game_types (id),
    cover_image_id     VARCHAR(255),
    version_title      TEXT,
    source_updated_at  TIMESTAMP WITH TIME ZONE,
    last_synced_at     TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX games_game_type_idx ON games (game_type_id);

CREATE TABLE game_platforms
(
    game_id     BIGINT NOT NULL REFERENCES games (id),
    platform_id BIGINT NOT NULL REFERENCES platforms (id),
    PRIMARY KEY (game_id, platform_id)
);
CREATE INDEX game_platforms_target_idx ON game_platforms (platform_id);

CREATE TABLE game_genres
(
    game_id  BIGINT NOT NULL REFERENCES games (id),
    genre_id BIGINT NOT NULL REFERENCES genres (id),
    PRIMARY KEY (game_id, genre_id)
);
CREATE INDEX game_genres_target_idx ON game_genres (genre_id);

CREATE TABLE game_engines
(
    game_id   BIGINT NOT NULL REFERENCES games (id),
    engine_id BIGINT NOT NULL REFERENCES engines (id),
    PRIMARY KEY (game_id, engine_id)
);
CREATE INDEX game_engines_target_idx ON game_engines (engine_id);

CREATE TABLE game_franchises
(
    game_id      BIGINT NOT NULL REFERENCES games (id),
    franchise_id BIGINT NOT NULL REFERENCES franchises (id),
    PRIMARY KEY (game_id, franchise_id)
);
CREATE INDEX game_franchises_target_idx ON game_franchises (franchise_id);

CREATE TABLE game_companies
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id    BIGINT  NOT NULL REFERENCES games (id),
    company_id BIGINT  NOT NULL REFERENCES companies (id),
    developer  BOOLEAN NOT NULL DEFAULT FALSE,
    publisher  BOOLEAN NOT NULL DEFAULT FALSE,
    porting    BOOLEAN NOT NULL DEFAULT FALSE,
    supporting BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (game_id, company_id)
);
CREATE INDEX game_companies_company_idx ON game_companies (company_id);

CREATE TABLE game_relations
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_game_id BIGINT      NOT NULL REFERENCES games (id),
    target_game_id BIGINT      NOT NULL REFERENCES games (id),
    relation_type  VARCHAR(40) NOT NULL,
    UNIQUE (source_game_id, target_game_id, relation_type),
    CONSTRAINT game_relations_no_self_reference CHECK (source_game_id <> target_game_id),
    CONSTRAINT game_relations_type_check CHECK (relation_type IN (
                                                                  'PARENT_GAME', 'VERSION_OF', 'DLC', 'EXPANSION',
                                                                  'STANDALONE_EXPANSION',
                                                                  'REMAKE', 'REMASTER', 'PORT', 'EXPANDED_GAME', 'FORK'
        ))
);
CREATE INDEX game_relations_target_idx ON game_relations (target_game_id);


-- #####  USERS  #####
CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)              NOT NULL UNIQUE,
    display_name  VARCHAR(100)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    enabled       BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_username_check CHECK (username ~ '^[a-z0-9][a-z0-9_-]{2,39}$'
)
    );

-- #####  ENTRIES  #####
CREATE TABLE entries
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT REFERENCES users (id) NOT NULL,
    title     VARCHAR(200)                 NOT NULL,
    score     DOUBLE PRECISION,
    status    VARCHAR(30)                  NOT NULL DEFAULT 'UNPLAYED',
    ownership VARCHAR(30),
    playtime  INTEGER,
    notes     VARCHAR(2000),
    CONSTRAINT entries_status_check CHECK (status IN
                                           ('COMPLETED', 'BEATEN', 'DROPPED', 'ON_HOLD', 'ENDLESS', 'UNPLAYED',
                                            'PLAYING')),
    CONSTRAINT entries_ownership_check CHECK (ownership IN
                                              ('OWN', 'HOUSEHOLD', 'FORMERLY_OWNED', 'OTHER', 'SUBSCRIPTION'))
);

CREATE INDEX entries_user_id_idx ON entries (user_id);

-- #####  PENDING GAME RELATIONS  #####
-- Keep only unresolved IGDB relationships until their target game is imported.
CREATE TABLE pending_game_relations
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_game_id BIGINT      NOT NULL REFERENCES games (id),
    target_igdb_id BIGINT      NOT NULL,
    relation_type  VARCHAR(40) NOT NULL,
    UNIQUE (source_game_id, target_igdb_id, relation_type),
    CONSTRAINT pending_game_relations_target_check CHECK (target_igdb_id > 0),
    CONSTRAINT pending_game_relations_type_check CHECK (relation_type IN (
                                                                          'PARENT_GAME', 'VERSION_OF', 'DLC',
                                                                          'EXPANSION', 'STANDALONE_EXPANSION',
                                                                          'REMAKE', 'REMASTER', 'PORT', 'EXPANDED_GAME',
                                                                          'FORK'
        ))
);
CREATE INDEX pending_game_relations_target_idx ON pending_game_relations (target_igdb_id);



-- #####  SPRING BATCH  #####
-- Spring Batch 6.0.6 official PostgreSQL schema, managed by Flyway.
-- Schema based on the official Spring Batch PostgreSQL metadata definitions.

CREATE TABLE BATCH_JOB_INSTANCE
(
    JOB_INSTANCE_ID BIGINT       NOT NULL PRIMARY KEY,
    VERSION         BIGINT,
    JOB_NAME        VARCHAR(100) NOT NULL,
    JOB_KEY         VARCHAR(32)  NOT NULL,
    constraint JOB_INST_UN unique (JOB_NAME, JOB_KEY)
);

CREATE TABLE BATCH_JOB_EXECUTION
(
    JOB_EXECUTION_ID BIGINT    NOT NULL PRIMARY KEY,
    VERSION          BIGINT,
    JOB_INSTANCE_ID  BIGINT    NOT NULL,
    CREATE_TIME      TIMESTAMP NOT NULL,
    START_TIME       TIMESTAMP DEFAULT NULL,
    END_TIME         TIMESTAMP DEFAULT NULL,
    STATUS           VARCHAR(10),
    EXIT_CODE        VARCHAR(2500),
    EXIT_MESSAGE     VARCHAR(2500),
    LAST_UPDATED     TIMESTAMP,
    constraint JOB_INST_EXEC_FK foreign key (JOB_INSTANCE_ID)
        references BATCH_JOB_INSTANCE (JOB_INSTANCE_ID)
);

CREATE TABLE BATCH_JOB_EXECUTION_PARAMS
(
    JOB_EXECUTION_ID BIGINT       NOT NULL,
    PARAMETER_NAME   VARCHAR(100) NOT NULL,
    PARAMETER_TYPE   VARCHAR(100) NOT NULL,
    PARAMETER_VALUE  VARCHAR(2500),
    IDENTIFYING      CHAR(1)      NOT NULL,
    constraint JOB_EXEC_PARAMS_FK foreign key (JOB_EXECUTION_ID)
        references BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE BATCH_STEP_EXECUTION
(
    STEP_EXECUTION_ID  BIGINT       NOT NULL PRIMARY KEY,
    VERSION            BIGINT       NOT NULL,
    STEP_NAME          VARCHAR(100) NOT NULL,
    JOB_EXECUTION_ID   BIGINT       NOT NULL,
    CREATE_TIME        TIMESTAMP    NOT NULL,
    START_TIME         TIMESTAMP DEFAULT NULL,
    END_TIME           TIMESTAMP DEFAULT NULL,
    STATUS             VARCHAR(10),
    COMMIT_COUNT       BIGINT,
    READ_COUNT         BIGINT,
    FILTER_COUNT       BIGINT,
    WRITE_COUNT        BIGINT,
    READ_SKIP_COUNT    BIGINT,
    WRITE_SKIP_COUNT   BIGINT,
    PROCESS_SKIP_COUNT BIGINT,
    ROLLBACK_COUNT     BIGINT,
    EXIT_CODE          VARCHAR(2500),
    EXIT_MESSAGE       VARCHAR(2500),
    LAST_UPDATED       TIMESTAMP,
    constraint JOB_EXEC_STEP_FK foreign key (JOB_EXECUTION_ID)
        references BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE BATCH_STEP_EXECUTION_CONTEXT
(
    STEP_EXECUTION_ID  BIGINT        NOT NULL PRIMARY KEY,
    SHORT_CONTEXT      VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    constraint STEP_EXEC_CTX_FK foreign key (STEP_EXECUTION_ID)
        references BATCH_STEP_EXECUTION (STEP_EXECUTION_ID)
);

CREATE TABLE BATCH_JOB_EXECUTION_CONTEXT
(
    JOB_EXECUTION_ID   BIGINT        NOT NULL PRIMARY KEY,
    SHORT_CONTEXT      VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    constraint JOB_EXEC_CTX_FK foreign key (JOB_EXECUTION_ID)
        references BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

